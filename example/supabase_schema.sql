create table if not exists public."TodayCategory" (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public."TodayTasks" (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  done boolean not null default false,
  do_later boolean not null default false,
  category_id bigint references public."TodayCategory"(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public."TodayCategory" enable row level security;
alter table public."TodayTasks" enable row level security;

create policy "Users can read their categories"
  on public."TodayCategory"
  for select
  to authenticated
  using (auth.uid() = user_id);

create policy "Users can insert their categories"
  on public."TodayCategory"
  for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Users can update their categories"
  on public."TodayCategory"
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can delete their categories"
  on public."TodayCategory"
  for delete
  to authenticated
  using (auth.uid() = user_id);

